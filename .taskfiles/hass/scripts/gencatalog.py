#!/usr/bin/env -S uv run --quiet --script
# /// script
# requires-python = ">=3.11"
# dependencies = ["pyyaml"]
# ///
"""Generate haconfig's purpose trigger and condition catalogs.

Usage: gencatalog.py CORE_DIR VERSION OUT_DIR

CORE_DIR is a checkout of home-assistant/core at release VERSION. It needs only
the files homeassistant/components/*/triggers.yaml and
homeassistant/components/*/conditions.yaml, so a sparse checkout works. OUT_DIR
is haconfig/models/frontend, and the script rewrites trigger/catalog.k and
condition/catalog.k under it.

Each catalog entry maps a purpose name, ``<domain>.<key>``, to the sorted keys
of that entry's ``fields``. Keys that start with ``.`` are YAML anchors, and the
script skips them. It also skips the domain-level ``_`` entry, because that
entry is the classic platform (``trigger: sun``), which haconfig models with its
own schema or covers with the Raw escape hatches.
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

GENERATOR = "task hass:gen"
"""The command named in each catalog's header, so a reader knows how to regenerate it."""


def collect(core: Path, kind: str) -> dict[str, list[str]]:
    """Map every purpose name in the KIND.yaml files under CORE to its option keys.

    The map follows the sorted component directory order, then each file's own
    key order.
    """
    found: dict[str, list[str]] = {}
    for path in sorted((core / "homeassistant" / "components").glob(f"*/{kind}.yaml")):
        domain = path.parent.name
        for key, body in (yaml.safe_load(path.read_text()) or {}).items():
            if key.startswith(".") or key == "_":
                continue
            fields = (body or {}).get("fields") or {}
            found[f"{domain}.{key}"] = sorted(fields)
    return found


def render(name: str, kind: str, version: str, entries: dict[str, list[str]]) -> str:
    """Return the KCL source of one catalog module."""
    rows = "\n".join(
        "    \"{}\" = [{}]".format(key, ", ".join(f'"{field}"' for field in fields))
        for key, fields in entries.items()
    )
    return (
        f"# Code generated by {GENERATOR} from Home Assistant {version}; DO NOT EDIT.\n"
        f'HA_VERSION = "{version}"\n'
        "\n"
        f"# {name} maps every purpose-specific {kind} name to its option keys.\n"
        f"{name}: {{str:[str]}} = {{\n{rows}\n}}\n"
    )


def main(argv: list[str]) -> int:
    if len(argv) != 4:
        print("usage: gencatalog.py CORE_DIR VERSION OUT_DIR", file=sys.stderr)
        return 2
    core, version, out = Path(argv[1]), argv[2], Path(argv[3])

    if not (core / "homeassistant" / "components").is_dir():
        print(f"gencatalog: {core} is not a home-assistant/core checkout", file=sys.stderr)
        return 1

    catalogs = (
        ("trigger", "TRIGGERS", "triggers"),
        ("condition", "CONDITIONS", "conditions"),
    )
    for package, name, kind in catalogs:
        entries = collect(core, kind)
        if not entries:
            print(f"gencatalog: no {kind}.yaml entries under {core}", file=sys.stderr)
            return 1
        dest = out / package / "catalog.k"
        if not dest.parent.is_dir():
            print(f"gencatalog: {dest.parent} does not exist", file=sys.stderr)
            return 1
        dest.write_text(render(name, kind.rstrip("s"), version, entries))
        print(f"{dest}: {len(entries)} {kind}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
