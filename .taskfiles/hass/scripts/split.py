#!/usr/bin/env -S uv run --quiet --script
# /// script
# requires-python = ">=3.11"
# dependencies = ["pyyaml"]
# ///
"""Split a haconfig render stream into a Home Assistant config directory.

Usage: split.py STREAM OUT

STREAM is the multi-document YAML that ``kcl run`` prints for a haconfig
config module. Each document holds exactly the keys ``path`` and ``content``. The
script parses and checks every document before it writes anything, then writes
the files into a temporary sibling of OUT and swaps that directory into place
after it writes the last file. A failed split leaves the previous OUT intact,
and a package removed from the config also loses its file.

The swap replaces OUT only when OUT is missing, empty, or a previous split's
output, which holds a ``configuration.yaml`` that starts with the haconfig
header. It refuses any other directory, so a mistyped OUT such as the repo root
fails instead of losing its files.

The script accepts only the paths haconfig emits: ``configuration.yaml``,
``secrets.example.yaml``, ``.gitignore``, and ``<dir>/<slug>.yaml``. It refuses
``secrets.yaml`` and the three UI-owned files by name. It also refuses a
duplicate path, content that still holds a tag sentinel, and a stream without
``configuration.yaml``.
"""

from __future__ import annotations

import os
import re
import shutil
import sys
import tempfile
from pathlib import Path

import yaml

ALLOWED = re.compile(
    r"configuration\.yaml|secrets\.example\.yaml|\.gitignore"
    r"|[a-z0-9_]+/[a-z0-9]+(_[a-z0-9]+)*\.yaml"
)
"""Paths the splitter writes, relative to OUT. Match with ``fullmatch``."""

HEADER = "# Code generated by haconfig"
"""The first line of every file that haconfig renders."""

SENTINEL = re.compile(r"\x00|\\(0|x00)!")
"""A tag sentinel that escaped untag, as a raw NUL or as the YAML escape yaml.encode writes."""

NEVER = frozenset({"secrets.yaml", "automations.yaml", "scripts.yaml", "scenes.yaml"})
"""Files that Home Assistant or the Pi own, refused even if ALLOWED matched."""


def parse(stream: Path) -> tuple[dict[str, str], list[str]]:
    """Parse STREAM into a map of relative path to file content.

    Returns the map and one message per problem found. The caller must not
    write anything when the message list is not empty.
    """
    files: dict[str, str] = {}
    problems: list[str] = []
    try:
        docs = list(yaml.safe_load_all(stream.read_text()))
    except (OSError, yaml.YAMLError) as err:
        return files, [f"{stream}: cannot parse the render stream: {err}"]

    for index, doc in enumerate(docs):
        if doc is None:
            continue
        if not isinstance(doc, dict) or set(doc) != {"path", "content"}:
            problems.append(f"document {index}: expected exactly the keys path and content, got {str(doc)[:80]!r}")
            continue
        path, content = doc["path"], doc["content"]
        if not isinstance(path, str) or not isinstance(content, str):
            problems.append(f"document {index}: path and content must both be strings")
            continue
        if path in NEVER or not ALLOWED.fullmatch(path):
            problems.append(f"{path!r}: refusing a path that haconfig does not own")
            continue
        if path in files:
            problems.append(f"{path!r}: duplicate path in the render stream")
            continue
        if SENTINEL.search(content):
            problems.append(f"{path}: holds a tag sentinel that escaped untag")
            continue
        files[path] = content

    if not problems and "configuration.yaml" not in files:
        problems.append("the render stream has no configuration.yaml")
    return files, problems


def replaceable(out: Path) -> str | None:
    """Return why the swap must not replace OUT, or None when it may.

    OUT may be replaced when it is missing, is an empty directory, or holds a
    ``configuration.yaml`` that starts with HEADER and no ``.git`` entry.
    """
    if not out.exists():
        return None
    if not out.is_dir():
        return f"{out}: exists and is not a directory"
    if (out / ".git").exists():
        return f"{out}: holds .git, refusing to replace a repository"
    if not any(out.iterdir()):
        return None
    try:
        first = (out / "configuration.yaml").read_text().partition("\n")[0]
    except OSError:
        first = ""
    if not first.startswith(HEADER):
        return f"{out}: not empty and not a haconfig render, refusing to replace it"
    return None


def write(files: dict[str, str], out: Path) -> None:
    """Write FILES into a fresh directory and swap it into place at OUT.

    FILES maps each path relative to OUT to its content. OUT must be absolute,
    and ``replaceable`` must have accepted it.
    """
    out.parent.mkdir(parents=True, exist_ok=True)
    tmp = Path(tempfile.mkdtemp(prefix=f".{out.name}.", dir=out.parent))
    old = out.with_name(f".{out.name}.old")
    try:
        for path, content in files.items():
            dest = tmp / path
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(content)
        # mkdtemp creates the directory as 0700. Match a normal directory so a
        # container that mounts OUT can read it.
        os.chmod(tmp, 0o755)
        if out.exists():
            shutil.rmtree(old, ignore_errors=True)
            os.rename(out, old)
        os.rename(tmp, out)
    except BaseException:
        # Put the previous OUT back when the second rename failed.
        if old.exists() and not out.exists():
            os.rename(old, out)
        shutil.rmtree(tmp, ignore_errors=True)
        raise
    shutil.rmtree(old, ignore_errors=True)


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print("usage: split.py STREAM OUT", file=sys.stderr)
        return 2
    stream, out = Path(argv[1]), Path(argv[2]).resolve()

    files, problems = parse(stream)
    if problems:
        for problem in problems:
            print(f"split: {problem}", file=sys.stderr)
        return 1

    refusal = replaceable(out)
    if refusal:
        print(f"split: {refusal}", file=sys.stderr)
        return 1

    write(files, out)
    # The file list goes to stderr, so a caller's stdout carries only its own
    # output, such as the diff that hass:diff prints.
    for path in sorted(files):
        print(out / path, file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
